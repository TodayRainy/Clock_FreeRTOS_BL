#!/usr/bin/env python3
"""Convert an existing RGB565 C array to the WeatherClock RLE format.

The original image arrays remain the byte-exact masters in the repository.
This script emits the compressed C file selected by CMake and decodes the
result before writing it, so a generator bug cannot silently alter pixels.

Packet format:

* bit 7 clear: 1..128 literal RGB565 pixels, followed by ``count * 2`` bytes;
* bit 7 set: 1..128 repeated pixels, followed by one two-byte RGB565 value.

The lower seven bits store ``count - 1``. Pixel byte order is preserved.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


ARRAY_RE = re.compile(
    r"static\s+const\s+(?:unsigned\s+char|uint8_t)\s+\w+\s*"
    r"\[(\d+)\]\s*=\s*\{(.*?)\};",
    re.IGNORECASE | re.DOTALL,
)
BYTE_RE = re.compile(r"0[xX]([0-9a-fA-F]{1,2})")
COMMENT_RE = re.compile(r"/\*.*?\*/|//[^\r\n]*", re.DOTALL)


def read_rgb565_array(path: Path) -> bytes:
    """Read the first fixed-size byte array from an image C source file."""

    source = path.read_text(encoding="utf-8")
    match = ARRAY_RE.search(source)
    if match is None:
        raise ValueError(f"no fixed-size image array found in {path}")

    expected_size = int(match.group(1))
    initializer = COMMENT_RE.sub("", match.group(2))
    data = bytes(int(value, 16) for value in BYTE_RE.findall(initializer))
    if len(data) != expected_size:
        raise ValueError(
            f"{path}: declared {expected_size} bytes, parsed {len(data)}"
        )
    if len(data) % 2:
        raise ValueError(f"{path}: RGB565 data length must be even")
    return data


def encode_rgb565(data: bytes) -> bytes:
    """Encode byte-exact RGB565 pixels using short PackBits-style packets."""

    pixels = [data[index : index + 2] for index in range(0, len(data), 2)]
    encoded = bytearray()
    index = 0

    while index < len(pixels):
        run = 1
        while (
            index + run < len(pixels)
            and run < 128
            and pixels[index + run] == pixels[index]
        ):
            run += 1

        if run >= 2:
            encoded.append(0x80 | (run - 1))
            encoded.extend(pixels[index])
            index += run
            continue

        literal_start = index
        index += 1
        while index - literal_start < 128 and index < len(pixels):
            next_run = 1
            while (
                index + next_run < len(pixels)
                and next_run < 128
                and pixels[index + next_run] == pixels[index]
            ):
                next_run += 1
            if next_run >= 2:
                break
            index += 1

        encoded.append(index - literal_start - 1)
        for pixel in pixels[literal_start:index]:
            encoded.extend(pixel)

    return bytes(encoded)


def decode_rgb565(data: bytes) -> bytes:
    """Reference decoder used to verify every generated stream."""

    decoded = bytearray()
    index = 0
    while index < len(data):
        control = data[index]
        index += 1
        count = (control & 0x7F) + 1

        if control & 0x80:
            pixel = data[index : index + 2]
            if len(pixel) != 2:
                raise ValueError("truncated repeated-pixel packet")
            index += 2
            decoded.extend(pixel * count)
        else:
            size = count * 2
            literal = data[index : index + size]
            if len(literal) != size:
                raise ValueError("truncated literal packet")
            index += size
            decoded.extend(literal)

    return bytes(decoded)


def format_array(data: bytes) -> str:
    """Format bytes in compact sixteen-byte C source rows."""

    rows = []
    for index in range(0, len(data), 16):
        values = ", ".join(f"0x{value:02X}" for value in data[index : index + 16])
        rows.append(f"    {values},")
    return "\n".join(rows)


def build_source(
    symbol: str, width: int, height: int, encoded: bytes, source_name: str
) -> str:
    """Build the generated image translation unit."""

    array_symbol = f"gImage_{symbol}_rle"
    return f'''/* Generated by scripts/encode_rgb565_rle.py from {source_name}. */
#include "image.h"

static const uint8_t {array_symbol}[{len(encoded)}] =
{{
{format_array(encoded)}
}};

const image_t {symbol} =
{{
    .width = {width},
    .height = {height},
    .data_size = sizeof({array_symbol}),
    .data = {array_symbol},
    .encoding = IMAGE_ENCODING_RGB565_RLE,
}};
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="raw RGB565 C source")
    parser.add_argument("output", type=Path, help="generated RLE C source")
    parser.add_argument("--symbol", required=True, help="exported image_t symbol")
    parser.add_argument("--width", required=True, type=int)
    parser.add_argument("--height", required=True, type=int)
    args = parser.parse_args()

    raw = read_rgb565_array(args.source)
    expected_size = args.width * args.height * 2
    if len(raw) != expected_size:
        raise ValueError(
            f"{args.symbol}: expected {expected_size} bytes for "
            f"{args.width}x{args.height}, got {len(raw)}"
        )

    encoded = encode_rgb565(raw)
    if decode_rgb565(encoded) != raw:
        raise RuntimeError(f"{args.symbol}: RLE round-trip verification failed")

    args.output.write_text(
        build_source(args.symbol, args.width, args.height, encoded, args.source.name),
        encoding="utf-8",
        newline="\n",
    )
    ratio = len(encoded) * 100.0 / len(raw)
    print(
        f"{args.symbol}: {len(raw)} -> {len(encoded)} bytes "
        f"({ratio:.1f}%, saved {len(raw) - len(encoded)})"
    )


if __name__ == "__main__":
    main()
